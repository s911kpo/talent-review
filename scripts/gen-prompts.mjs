// Bundles the editable prompts/*.md into a module, so deployment needs no static file support.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = 'supabase/functions/ai-generate/prompts';
const entries = readdirSync(dir).filter((f) => f.endsWith('.md')).sort()
  .map((f) => [f.replace(/\.md$/, ''), readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim()]);

writeFileSync(
  'supabase/functions/ai-generate/prompts.generated.ts',
  `// GENERATED by scripts/gen-prompts.mjs. Edit prompts/*.md, then run npm run prompts:gen.\nexport const PROMPTS: Record<string, string> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};\n`,
  'utf8',
);
console.log(`Bundled ${entries.length} prompts.`);
