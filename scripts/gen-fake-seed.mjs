// Generates supabase/seed/fake_seed.sql, supabase/seed/demo_accounts.json and docs/DEMO_ACCOUNTS.md.
// Everyone here is invented. Shape mirrors SPEC section 13: 122 people, 108 in scope, 11 reviewers.
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CYCLE_ID = '11111111-1111-4111-8111-111111111111';

const surnames = [
  ['Chen', '陳'], ['Lin', '林'], ['Huang', '黃'], ['Chang', '張'], ['Lee', '李'],
  ['Wang', '王'], ['Wu', '吳'], ['Liu', '劉'], ['Tsai', '蔡'], ['Yang', '楊'],
];
const givens = [
  ['Alder', '赤楊'], ['Birch', '白樺'], ['Cedar', '雪松'], ['Dune', '沙丘'], ['Ember', '餘燼'],
  ['Fern', '蕨葉'], ['Grove', '樹林'], ['Hazel', '榛果'], ['Iris', '鳶尾'], ['Juniper', '杜松'],
  ['Kestrel', '紅隼'], ['Linden', '椴樹'], ['Maple', '楓葉'],
];
const depts = [
  ['Process Engineering', '5101'], ['Quality', '5102'], ['Production', '5103'],
  ['R&D', '5104'], ['Supply Chain', '5105'], ['Equipment', '5106'],
];
const titles = ['Process Engineer', 'Sr. Process Engineer', 'Quality Engineer', 'Technician', 'Production Planner', 'Equipment Engineer'];

const people = new Map();
let id = 900000;
const next = () => ++id;

function add(employeeId, supervisorId, inScope, position, deptIndex) {
  const s = surnames[employeeId % surnames.length];
  const g = givens[(employeeId * 7) % givens.length];
  const dept = depts[deptIndex % depts.length];
  const year = 2012 + (employeeId % 14);
  const month = String((employeeId % 12) + 1).padStart(2, '0');
  people.set(employeeId, {
    employeeId, supervisorId, inScope, position, dept: dept[0], deptNo: dept[1],
    fullName: `${s[0]}, ${g[0]}${employeeId % 100}`,
    localName: `${s[1]}${g[1]}`,
    gender: employeeId % 2 === 0 ? 'F' : 'M',
    startDate: `${year}-${month}-15`,
  });
}

// GM: external supervisor, so outside this review.
const gm = next();
add(gm, 0, false, 'General Manager', 0);

// Five managers who report to the GM and are themselves reviewed.
const subManagers = Array.from({ length: 5 }, (_, i) => {
  const m = next();
  add(m, gm, true, 'Supervisor', i);
  return m;
});

// Ten individual contributors under the GM (GM direct total: 15).
for (let i = 0; i < 10; i++) add(next(), gm, true, 'Program Manager', i);

// Five more reviewers whose supervisors are outside the site (with the GM, six in total).
const otherManagers = Array.from({ length: 5 }, (_, i) => {
  const m = next();
  add(m, 0, false, 'Supervisor', i + 1);
  return m;
});

// Eight further out-of-scope people, which brings out-of-scope to 14.
for (let i = 0; i < 8; i++) add(next(), 0, false, 'Site Support', i);

// 93 people across ten teams, which brings in-scope to 108.
const teamSizes = [10, 10, 10, 9, 9, 9, 9, 9, 9, 9];
[...subManagers, ...otherManagers].forEach((manager, t) => {
  for (let i = 0; i < teamSizes[t]; i++) add(next(), manager, true, titles[i % titles.length], t);
});

const all = [...people.values()];
const inScope = all.filter((p) => p.inScope).length;
const reviewers = [...new Set(all.filter((p) => p.inScope).map((p) => p.supervisorId))];
if (all.length !== 122 || inScope !== 108 || reviewers.length !== 11) {
  throw new Error(`Shape mismatch: ${all.length} people, ${inScope} in scope, ${reviewers.length} reviewers`);
}

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const nameOf = (eid) => (eid === 0 ? 'External Supervisor' : people.get(eid).fullName);

const lines = [
  '-- GENERATED by scripts/gen-fake-seed.mjs. Fictional people only. Never add real employees here.',
  'insert into public.cycles (id, code, quarter_label, site, status, open_at, due_at) values',
  `  (${q(CYCLE_ID)}, 'Q4-2026', 'Q4 2026', 'Xindian', 'open', '2026-11-13T00:00:00+08', '2026-11-30T23:59:59+08')`,
  'on conflict (id) do nothing;',
  '',
  'insert into public.employees (employee_id, local_name, full_name, gender, start_date) values',
  all.map((p) => `  (${p.employeeId}, ${q(p.localName)}, ${q(p.fullName)}, ${q(p.gender)}, ${q(p.startDate)})`).join(',\n'),
  'on conflict (employee_id) do nothing;',
  '',
  'insert into public.cycle_population (cycle_id, employee_id, in_scope, supervisor_id, supervisor_name_raw, dept, dept_no, position) values',
  all.map((p) => `  (${q(CYCLE_ID)}, ${p.employeeId}, ${p.inScope}, ${p.supervisorId}, ${q(nameOf(p.supervisorId))}, ${q(p.dept)}, ${q(p.deptNo)}, ${q(p.position)})`).join(',\n'),
  'on conflict (cycle_id, employee_id) do nothing;',
  '',
];
mkdirSync(join(root, 'supabase/seed'), { recursive: true });
writeFileSync(join(root, 'supabase/seed/fake_seed.sql'), lines.join('\n'), 'utf8');

// Fixed demo PINs from a small deterministic generator, for staging walkthroughs only.
const ALPHABET = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
let state = 20261110;
const rand = () => (state = (state * 1103515245 + 12345) & 0x7fffffff);
const demoPin = () => Array.from({ length: 8 }, () => ALPHABET[(rand() >> 8) % ALPHABET.length]).join('');

const managers = reviewers.sort((a, b) => a - b).map((employeeId) => ({
  employeeId, name: people.get(employeeId).fullName, pin: demoPin(),
  note: employeeId === gm ? 'GM: sees all five sub-manager lines read-only'
    : subManagers.includes(employeeId) ? 'Reports to the GM: also reviewed by the GM'
    : 'Supervisor is external',
}));
const hr = { email: 'demo-hr@talentreview.local', password: 'Demo-HR-Staging-2026', displayName: 'Demo HR' };
writeFileSync(join(root, 'supabase/seed/demo_accounts.json'), JSON.stringify({ managers, hr }, null, 2) + '\n', 'utf8');

const md = [
  '# Demo accounts',
  '',
  'Fictional accounts for staging walkthroughs. Create them with `npm run demo:provision`.',
  '',
  '**Remove them before real data goes in: `npm run demo:remove`.** These credentials are stored in the repo, so a demo HR account left on the live system would expose everything.',
  '',
  '## Managers',
  '',
  '| Employee ID | Name | PIN | Note |',
  '|---|---|---|---|',
  ...managers.map((m) => `| ${m.employeeId} | ${m.name} | ${m.pin} | ${m.note} |`),
  '',
  '## HR',
  '',
  `- Email: ${hr.email}`,
  `- Password: ${hr.password}`,
  '',
].join('\n');
mkdirSync(join(root, 'docs'), { recursive: true });
writeFileSync(join(root, 'docs/DEMO_ACCOUNTS.md'), md, 'utf8');

console.log(`Generated ${all.length} people, ${inScope} in scope, ${reviewers.length} reviewers.`);
